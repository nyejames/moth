"""Regenerate the body-local numeric and grouped-not scaling fixtures."""

from pathlib import Path


SIZES = (32, 128, 512)
# Per-query alias cost hides under constant overhead below a few thousand bindings.
SHAPE_SIZES = {
    "alias-receiver-chain": (256, 1024, 4096),
    # Runtime HIR needs deeper chains to clear the scaling measurement floor.
    "grouped-not-runtime": (128, 512, 2048),
}
ROOT = Path(__file__).resolve().parent


def fixture(shape, size):
    lines = [f"-- Generated by benchmarks/numeric-scaling/generate.py: {shape}, size {size}."]
    if shape == "copy-chain":
        lines += ["chain || -> U64:", "    value_0 = 1"]
        lines += [f"    value_{i} = copy value_{i - 1}" for i in range(1, size + 1)]
        lines += [f"    return value_{size}", ";"]
    elif shape == "origin-fanout":
        lines += ["accept |value U64|:", ";", "fanout ||:", "    origin = 1"]
        lines += [f"    use_{i} = copy origin\n    accept(use_{i})" for i in range(size)]
        lines += [";"]
    elif shape == "alias-receiver-chain":
        lines += ["accept |value U64|:", ";", "chain ||:", "    value_0 = 1"]
        lines += [f"    value_{i} = copy value_{i - 1}\n    accept(value_{i})" for i in range(1, size + 1)]
        lines += [";"]
    elif shape == "generic-failure-chain":
        lines += ["identity type T |value T| -> T:", "    return value", ";"]
        for i in range(size):
            lines += [f"step_{i} |value I32| -> I32:", f"    return step_{i + 1}(value)", ";"]
        lines += [f"step_{size} |value I32| -> I32:", "    return value + 1", ";"]
        lines += ["unrelated |seed I32| -> I32:", "    total_0 = seed"]
        lines += [f"    total_{i} = total_{i - 1} + seed" for i in range(1, size + 1)]
        lines += [f"    return total_{size}", ";"]
        lines += ["result I32 = step_0(identity(1)) catch then 0"]
    elif shape == "grouped-arithmetic":
        expression = "1"
        for _ in range(size):
            expression = f"({expression} + 1)"
        lines += ["grouped || -> U64:", f"    value = {expression}", "    return value", ";"]
    elif shape == "grouped-not-runtime":
        expression = "not (" * size + "value" + ")" * size
        lines += ["grouped |value Bool| -> Bool:", f"    return {expression}", ";"]
    elif shape == "independent-regions":
        lines += ["regions ||:"]
        lines += [f"    origin_{i} = 1 + 2\n    received_{i} U64 = origin_{i}" for i in range(size)]
        lines += [";"]
    elif shape == "aggregate-forwarding":
        lines += ["identity type T |value T| -> T:", "    return value", ";", "aggregates ||:"]
        for i in range(size):
            lines += [f"    items_{i} = {{1, 2}}", f"    forwarded_items_{i} = identity(items_{i})", f"    received_items_{i} {{U64}} = forwarded_items_{i}", f"    map_{i} = {{1 = 2, 3 = 4}}", f"    forwarded_map_{i} = identity(map_{i})", f"    received_map_{i} {{U64 = U64}} = forwarded_map_{i}"]
        lines += [";"]
    elif shape == "safety-pruning":
        lines += ["identity type T |value T| -> T:", "    return value", ";", "safety ||:", "    captured U64 = 7"]
        for i in range(size):
            lines += [f"    result_{i} U64 = 1 + 2 catch |failure_{i}|:", f"        fallback_{i} = identity(captured)", f"        message_{i} = failure_{i}.message", f"        then fallback_{i}", "    ;"]
        lines += [";"]
    elif shape == "mutable-cycles":
        lines += ["cycles |concrete I64|:"]
        for i in range(size):
            lines += [f"    left_{i} ~= 1", f"    right_{i} ~= 2", f"    ~left_{i} = copy right_{i}", f"    ~right_{i} = copy left_{i}", f"    mixed_{i} I64 = concrete + left_{i}", f"    received_{i} I64 = right_{i}"]
        lines += [";"]
    elif shape == "narrow-chains":
        for name, numeric_type in (("signed", "I8"), ("unsigned", "U8"), ("half", "F16")):
            lines += [f"{name} |seed {numeric_type}, step {numeric_type}| -> {numeric_type}:", "    value_0 = seed"]
            lines += [f"    value_{i} = value_{i - 1} + step" for i in range(1, size + 1)]
            lines += [f"    return value_{size}", ";"]
    else:
        raise ValueError(shape)
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    for shape in (
        "copy-chain",
        "origin-fanout",
        "alias-receiver-chain",
        "grouped-arithmetic",
        "grouped-not-runtime",
        "independent-regions",
        "aggregate-forwarding",
        "safety-pruning",
        "mutable-cycles",
        "narrow-chains",
        "generic-failure-chain",
    ):
        for size in SHAPE_SIZES.get(shape, SIZES):
            (ROOT / f"{shape}-{size}.moth").write_text(fixture(shape, size))
